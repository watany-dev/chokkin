//! `pdm.lock` graph extraction.

use std::path::Path;

use toml::Value;

use super::error::ManifestError;
use super::lockfile::{
    array_tables, merge_extra, merge_package, read_lock_table, requirement_extras,
};
use super::pep508_util::{
    extract_egg_name, is_strict_pep508_name, leading_name_token, normalize_distribution_name,
};
use super::types::LockfileGraph;

/// Parse `pdm.lock` (pdm 2.x) into a dependency name graph.
///
/// `groups` are dropped: declaration contexts come from the manifest, and the
/// graph only answers "reachable from a declared dependency". A package
/// requested with extras is its own entry with `extras = [...]`, whose
/// `dependencies` are the base package plus what the extras add; those are
/// read as each extra's additions (#1376) and still merged into the base
/// edges, as before extras were read.
pub(super) fn extract_pdm_lock(path: &Path) -> Result<LockfileGraph, ManifestError> {
    let table = read_lock_table(path)?;
    let mut graph = LockfileGraph::default();
    for package in array_tables(&table, "package") {
        let Some(name) = package.get("name").and_then(Value::as_str) else {
            continue;
        };
        let deps: Vec<(String, Vec<String>)> = package
            .get("dependencies")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter_map(Value::as_str)
            .filter_map(|spec| Some((requirement_name(spec)?, requirement_extras(spec))))
            .collect();
        let normalized = normalize_distribution_name(name);
        graph.add_edge_extras(&normalized, "", &deps);
        let extras = package
            .get("extras")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter_map(Value::as_str);
        let added: Vec<(String, Vec<String>)> = deps
            .iter()
            .filter(|(dep, _)| *dep != normalized)
            .cloned()
            .collect();
        for extra in extras {
            merge_extra(&mut graph, name, extra, &added);
        }
        merge_package(&mut graph.edges, name, deps.into_iter().map(|(dep, _)| dep));
    }
    Ok(graph)
}

/// Distribution name at the head of a PEP 508 string such as
/// `urllib3<3,>=1.21.1` or `requests[socks]==2.31.0; python_version >= "3.8"`,
/// or the `#egg=` name of an editable `-e file:///...#egg=name` entry.
fn requirement_name(spec: &str) -> Option<String> {
    let name = leading_name_token(spec.trim_start());
    if is_strict_pep508_name(name) {
        Some(normalize_distribution_name(name))
    } else {
        extract_egg_name(spec)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn parse(contents: &str) -> Result<LockfileGraph, ManifestError> {
        let temp = tempfile::tempdir().expect("tempdir");
        let path = temp.path().join("pdm.lock");
        std::fs::write(&path, contents).expect("write pdm.lock");
        extract_pdm_lock(&path)
    }

    const PDM_2_LOCK: &str = r#"
# This file is @generated by PDM.
# It is not intended for manual editing.

[metadata]
groups = ["default", "dev"]
strategy = ["inherit_metadata"]
lock_version = "4.5.0"
content_hash = "sha256:abc"

[[metadata.targets]]
requires_python = ">=3.11"

[[package]]
name = "requests"
version = "2.32.3"
requires_python = ">=3.8"
summary = "Python HTTP for Humans."
groups = ["default"]
dependencies = [
    "certifi>=2017.4.17",
    "charset-normalizer<4,>=2",
    "idna<4,>=2.5",
    "urllib3<3,>=1.21.1",
]
files = [
    {file = "requests-2.32.3-py3-none-any.whl", hash = "sha256:70761cfe"},
]

[[package]]
name = "requests"
version = "2.32.3"
extras = ["socks"]
requires_python = ">=3.8"
groups = ["default"]
dependencies = [
    "PySocks!=1.5.7,>=1.5.6",
    "requests==2.32.3",
]

[[package]]
name = "urllib3"
version = "2.2.3"
requires_python = ">=3.8"
groups = ["default"]

[[package]]
name = "pytest"
version = "8.3.3"
groups = ["dev"]
dependencies = [
    "colorama; sys_platform == \"win32\"",
    "iniconfig",
]
"#;

    #[test]
    fn extracts_pdm_2_lock() {
        let graph = parse(PDM_2_LOCK).expect("valid pdm.lock");
        assert_eq!(
            graph.edges.get("requests"),
            Some(&vec![
                "certifi".to_owned(),
                "charset-normalizer".to_owned(),
                "idna".to_owned(),
                "urllib3".to_owned(),
                "pysocks".to_owned(),
                "requests".to_owned(),
            ])
        );
        assert_eq!(
            graph.edges.get("pytest"),
            Some(&vec!["colorama".to_owned(), "iniconfig".to_owned()])
        );
        assert_eq!(graph.edges.get("urllib3"), Some(&Vec::new()));
    }

    /// An extras entry's dependencies, less the package itself, are what its
    /// extras add (#1376).
    #[test]
    fn extracts_extras_from_extras_entries() {
        let graph = parse(concat!(
            "[[package]]\nname = \"psycopg\"\nversion = \"3.2\"\ndependencies = [\"typing-extensions\"]\n\n",
            "[[package]]\nname = \"psycopg\"\nversion = \"3.2\"\nextras = [\"pool\", \"Binary\"]\n",
            "dependencies = [\"psycopg==3.2\", \"psycopg-pool\", \"psycopg-binary[x]==3.2\"]\n",
        ))
        .expect("valid pdm.lock");
        let added = vec!["psycopg-pool".to_owned(), "psycopg-binary".to_owned()];
        assert_eq!(
            graph.extras.get("psycopg"),
            Some(&std::collections::BTreeMap::from([
                ("binary".to_owned(), added.clone()),
                ("pool".to_owned(), added),
            ]))
        );
        assert_eq!(
            graph
                .edge_extras
                .get("psycopg")
                .and_then(|by_extra| by_extra.get("pool"))
                .and_then(|deps| deps.get("psycopg-binary")),
            Some(&vec!["x".to_owned()])
        );
        assert_eq!(
            graph.edges.get("psycopg"),
            Some(&vec![
                "typing-extensions".to_owned(),
                "psycopg".to_owned(),
                "psycopg-pool".to_owned(),
                "psycopg-binary".to_owned(),
            ])
        );
    }

    #[test]
    fn requirement_name_stops_at_first_non_name_character() {
        assert_eq!(requirement_name("urllib3<3"), Some("urllib3".to_owned()));
        assert_eq!(
            requirement_name(" Foo_Bar[x]==1; os_name == 'nt'"),
            Some("foo-bar".to_owned())
        );
        assert_eq!(requirement_name("idna"), Some("idna".to_owned()));
        assert_eq!(
            requirement_name("-e file:///${PROJECT_ROOT}/packages/foo#egg=foo"),
            Some("foo".to_owned())
        );
        assert_eq!(
            requirement_name("-e file:///${PROJECT_ROOT}/packages/foo"),
            None
        );
        assert_eq!(requirement_name(">=1"), None);
        assert_eq!(requirement_name(""), None);
    }

    #[test]
    fn rejects_invalid_toml() {
        let error = parse("[[package\n").expect_err("invalid TOML");
        assert!(matches!(error, ManifestError::InvalidLockfile { .. }));
    }

    mod props {
        use super::*;
        use proptest::prelude::*;

        proptest! {
            #[test]
            fn extract_pdm_lock_never_panics(contents in "\\PC{0,400}") {
                let _ = parse(&contents);
            }

            #[test]
            fn requirement_name_never_panics(spec in "\\PC{0,60}") {
                if let Some(name) = requirement_name(&spec) {
                    prop_assert_eq!(normalize_distribution_name(&name), name);
                }
            }
        }
    }
}
