    /// Dependency order follows the TOML map, which may or may not preserve
    /// insertion order depending on crate features.
    fn sorted_deps(graph: &LockfileGraph, name: &str) -> Vec<String> {
        let mut deps = graph.edges.get(name).cloned().expect("package present");
        deps.sort();
        deps
    }

    #[test]
    fn extracts_lock_version_1_1() {
        let graph = parse(LOCK_V1_1).expect("valid poetry.lock 1.1");
        assert_eq!(
            sorted_deps(&graph, "requests"),
            vec!["certifi", "charset-normalizer", "urllib3"]
        );
        assert_eq!(sorted_deps(&graph, "urllib3"), Vec::<String>::new());
        assert_eq!(graph.edges.len(), 2);
    }

    #[test]
    fn extracts_lock_version_2_0() {
        let graph = parse(LOCK_V2_0).expect("valid poetry.lock 2.0");
        assert_eq!(
            sorted_deps(&graph, "flask"),
            vec!["blinker", "colorama", "importlib-metadata", "werkzeug"]
        );
        assert_eq!(sorted_deps(&graph, "werkzeug"), Vec::<String>::new());
    }

    /// `[package.extras]` and a dependency table's `extras` (#1376).
    #[test]
    fn extracts_extras_and_edge_extras() {
        let graph = parse(concat!(
            "[[package]]\nname = \"FastAPI\"\nversion = \"0.115\"\n\n",
            "[package.dependencies]\nstarlette = \">=0.40\"\n",
            "uvicorn = {version = \">=0.12\", optional = true, extras = [\"Standard\"]}\n",
            "httpx = [{version = \"*\", markers = \"x\", extras = [\"http2\"]}, {version = \"*\", extras = [\"http2\", \"brotli\"]}]\n\n",
            "[package.extras]\nall = [\"uvicorn[standard] (>=0.12)\", \"email-validator (>=2)\", \"(bad)\"]\nnone = []\n",
        ))
        .expect("valid poetry.lock");
        assert_eq!(
            graph.extras.get("fastapi"),
            Some(&BTreeMap::from([
                (
                    "all".to_owned(),
                    vec!["uvicorn".to_owned(), "email-validator".to_owned()]
                ),
                ("none".to_owned(), Vec::new()),
            ]))
        );
        let edge_extras = graph.edge_extras.get("fastapi").expect("edge extras");
        assert_eq!(
            edge_extras.get(""),
            Some(&BTreeMap::from([
                (
                    "httpx".to_owned(),
                    vec!["http2".to_owned(), "brotli".to_owned()]
                ),
                ("uvicorn".to_owned(), vec!["standard".to_owned()]),
            ]))
        );
        assert_eq!(
            edge_extras.get("all"),
            Some(&BTreeMap::from([(
                "uvicorn".to_owned(),
                vec!["standard".to_owned()]
            )]))
        );
    }

    #[test]
    fn rejects_invalid_toml() {
        let error = parse("[[package\n").expect_err("invalid TOML");
        assert!(matches!(error, ManifestError::InvalidLockfile { .. }));
    }

