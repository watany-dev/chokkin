"""Emit Lexical/CodecTable.lean from CPython's `encodings` package.

The table is data from the reference implementation (Lib/encodings/aliases.py
and the codec modules next to it), not from chokkin. Run with the Python whose
behaviour is the reference (3.13 for this ledger):

    python3 -I scripts/gen_codecs.py > Lexical/CodecTable.lean
"""

import codecs
import encodings
import encodings.aliases
import os
import sys

pkg = os.path.dirname(encodings.__file__)
modules = sorted(
    name[:-3]
    for name in os.listdir(pkg)
    if name.endswith(".py") and name not in ("__init__.py", "aliases.py")
)
text = []
for m in modules:
    try:
        info = codecs.lookup(m)
    except LookupError:
        continue
    if getattr(info, "_is_text_encoding", True):
        text.append(m)


def lean_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


print(
    "/-! Generated by `scripts/gen_codecs.py` from CPython",
    sys.version.split()[0],
    "`encodings`. Do not edit. -/",
)
print("namespace Lexical")
print("/-- `encodings.aliases.aliases`: normalized alias → codec module. -/")
print("def aliasTable : List (String × String) := [")
print(
    ",\n".join(
        f"  ({lean_str(k)}, {lean_str(v)})"
        for k, v in sorted(encodings.aliases.aliases.items())
    )
)
print("]")
print("/-- Codec modules of `encodings` that are text encodings. -/")
print("def textCodecs : List String := [")
print(",\n".join(f"  {lean_str(m)}" for m in text))
print("]")
print("end Lexical")
