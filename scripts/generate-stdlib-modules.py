#!/usr/bin/env python3
"""Generate the versioned stdlib module table for chokkin resolver.

Each version's set is ``sys.stdlib_module_names`` of the matching
interpreter, so version differences (3.11 ``tomllib``, 3.12 ``distutils``
removal, 3.13 PEP 594 removals) come from CPython itself. 3.8 and 3.9 predate
``sys.stdlib_module_names`` and are written as differences from 3.10. The list
is a static table in CPython, so it is identical across platforms (``msvcrt`` /
``winreg`` are listed on Linux too).

The sets are merged into one table where each root carries the minors that
ship it, since only a few dozen roots differ between versions.

Every ``python3.X`` in VERSIONS must be on PATH (CI installs them with
actions/setup-python).
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "resolver" / "stdlib" / "modules.txt"

VERSIONS = ["3.10", "3.11", "3.12", "3.13", "3.14", "3.15"]

# `sys.stdlib_module_names` is 3.10+, so each older minor is the next one's
# set with these roots added and removed. They are what the stdlib and
# lib-dynload directories and `sys.builtin_module_names` of CPython 3.8.20,
# 3.9.25 and 3.10.20 differ by, test modules aside as
# `sys.stdlib_module_names` sets them aside (#940).
OLDER_MINORS = {
    9: (
        {"_bootlocale", "_peg_parser", "formatter", "parser", "symbol"},
        set(),
    ),
    8: (
        {"_dummy_thread", "dummy_threading"},
        {"_aix_support", "_bootsubprocess", "_peg_parser", "_zoneinfo", "graphlib", "zoneinfo"},
    ),
}

# `__main__` is always importable but `sys.stdlib_module_names` omits it.
ALWAYS_PRESENT = ["__main__"]

DUMP = "import sys; print('\\n'.join(sorted(sys.stdlib_module_names)))"

HEADER = """\
# Generated by scripts/generate-stdlib-modules.py; do not edit.
# `sys.stdlib_module_names` of Python {first}-{last}, plus `__main__` (minors
# before 3.10 come from OLDER_MINORS in the script).
# `name first-last` lists the Python 3 minors that ship `name`: a bare name
# ships in every one, and an empty `last` means up to the newest.
"""


def stdlib_module_names(version: str) -> set[str]:
    python = shutil.which(f"python{version}")
    if python is None:
        raise SystemExit(f"python{version} not found on PATH")
    out = subprocess.run(
        [python, "-c", DUMP],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return {*out.split(), *ALWAYS_PRESENT}


def annotate(modules: dict[int, set[str]]) -> list[str]:
    minors = sorted(modules)
    oldest, newest = minors[0], minors[-1]
    lines = []
    for name in sorted(set().union(*modules.values())):
        shipped = [m for m in minors if name in modules[m]]
        first, last = shipped[0], shipped[-1]
        if shipped != list(range(first, last + 1)):
            raise SystemExit(f"{name} leaves and returns: {shipped}")
        if (first, last) == (oldest, newest):
            lines.append(name)
        else:
            lines.append(f"{name} {first}-{'' if last == newest else last}")
    return lines


def add_older_minors(modules: dict[int, set[str]]) -> None:
    for minor, (added, removed) in sorted(OLDER_MINORS.items(), reverse=True):
        newer = modules[minor + 1]
        if not removed <= newer or added & newer:
            raise SystemExit(f"3.{minor} differences do not fit 3.{minor + 1}")
        modules[minor] = (newer - removed) | added


def main() -> None:
    modules = {int(v.split(".")[1]): stdlib_module_names(v) for v in VERSIONS}
    add_older_minors(modules)
    lines = annotate(modules)
    header = HEADER.format(first=f"3.{min(modules)}", last=VERSIONS[-1])
    OUT.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines)} modules)")


if __name__ == "__main__":
    main()
